/**
 * Astro's local font provider, plus a `subset` tag ("core" or "extended") on
 * each face so `<Font preload={[{ subset: "core" }]} />` can skip the
 * extended files. Both files of a face share one font family, so the browser
 * tries the extended file before the generated fallback face.
 */
function subsetFontProvider() {
  const local = fontProviders.local();
  return {
    name: "local-subsets",
    init: (context) => local.init(context),
    resolveFont(options) {
      const variants = options.options?.variants ?? [];
      const { fonts } = local.resolveFont(options);
      return {
        fonts: fonts.map((font, index) => ({
          ...font,
          meta: { ...font.meta, subset: variants[index].subset },
        })),
      };
    },
  };
}

/** @param {keyof typeof subsetFonts.families} key */
function subsetFontFamily(key, cssVariable, fallbacks) {
  const { name, faces } = subsetFonts.families[key];
  return {
    provider: subsetFontProvider(),
    name,
    cssVariable,
    fallbacks,
    options: {
      variants: faces.map(({ src, ...face }) => ({ ...face, src: [src] })),
    },
  };
}

